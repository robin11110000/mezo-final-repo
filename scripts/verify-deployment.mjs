import {readFile,writeFile} from 'node:fs/promises';
import {createPublicClient,http,getAddress,parseAbi,keccak256} from 'viem';
const base=new URL('../',import.meta.url);
const artifact=JSON.parse(await readFile(new URL('exports/WorkingCapitalVault.json',base),'utf8'));
const compatibility=JSON.parse(await readFile(new URL('exports/runtime-compatibility.json',base),'utf8'));
const manifest=JSON.parse(await readFile(new URL('integrations/testnet/manifest.json',base),'utf8'));
const address=getAddress(process.argv[2]??'');
const expectedOwner=getAddress(process.argv[3]??'');
const client=createPublicClient({transport:http('https://rpc.test.mezo.org',{timeout:20000,retryCount:0})});
if(await client.getChainId()!==31611)throw new Error('Mezo testnet required');
const blockNumber=await client.getBlockNumber(),code=await client.getCode({address,blockNumber});
if(!code||code==='0x')throw new Error('No deployed contract');
let masked=code.slice(2).toLowerCase();
for(const refs of Object.values(artifact.immutableReferences))for(const {start,length} of refs)masked=masked.slice(0,start*2)+'0'.repeat(length*2)+masked.slice((start+length)*2);
const templates=[artifact.runtimeTemplate,...(compatibility.sourceHash===artifact.sourceHash?compatibility.acceptedRuntimeTemplates:[])];
if(!templates.some(template=>masked===template.slice(2).toLowerCase()))throw new Error('Unrecognized executable build');
const read=functionName=>client.readContract({address,abi:artifact.abi,functionName,blockNumber});
const [owner,musd,savings,snapshot,initialStrategy]=await Promise.all(['owner','musd','savings','snapshot','initialStrategy'].map(read));
if(getAddress(owner)!==expectedOwner||getAddress(musd)!==getAddress(manifest.contracts.musd.address)||getAddress(savings)!==getAddress(manifest.contracts.savings.address))throw new Error('Unexpected owner or integration targets');
const report={chainId:31611,address,owner,blockNumber,runtimeCodeHash:keccak256(code),runtimeVerified:true,musd,savings,initialStrategy,liquidMusd:snapshot[0],savingsPrincipal:snapshot[1],active:snapshot[2].active,minedFundedLifecycleVerified:false};
const json=JSON.stringify(report,(_,v)=>typeof v==='bigint'?v.toString():v,2)+'\n';
await writeFile(new URL('exports/deployment.json',base),json);
await writeFile(new URL('ui/src/lib/deployment.json',base),json);
console.log(json);
